// HTTP status to string code mapping
const STATUS_CODES = require("./statusCode");

const ERROR_CODES = {
    [STATUS_CODES.BAD_REQUEST]: "BAD_REQUEST",
    [STATUS_CODES.UNAUTHORIZED]: "UNAUTHORIZED",
    [STATUS_CODES.PAYMENT_REQUIRED]: "PAYMENT_REQUIRED",
    [STATUS_CODES.FORBIDDEN]: "FORBIDDEN",
    [STATUS_CODES.NOT_FOUND]: "NOT_FOUND",
    [STATUS_CODES.CONFLICT]: "CONFLICT",
    [STATUS_CODES.METHOD_NOT_ALLOWED]: "METHOD_NOT_ALLOWED",
    [STATUS_CODES.NOT_ACCEPTABLE]: "NOT_ACCEPTABLE",
    [STATUS_CODES.REQUEST_TIMEOUT]: "REQUEST_TIMEOUT",
    [STATUS_CODES.TOO_MANY_REQUESTS]: "TOO_MANY_REQUESTS",
    [STATUS_CODES.INTERNAL_SERVER_ERROR]: "INTERNAL_SERVER_ERROR",
    [STATUS_CODES.SERVICE_UNAVAILABLE]: "SERVICE_UNAVAILABLE",
    [STATUS_CODES.GATEWAY_TIMEOUT]: "GATEWAY_TIMEOUT",
};

function getErrorCode(statusCode) {
    return ERROR_CODES[statusCode] || "INTERNAL_SERVER_ERROR";
}

module.exports = { ERROR_CODES, getErrorCode };
