const { randomUUID } = require('crypto');
const mongoose = require('mongoose');

// This is deliberately separate from the subscription Payment model. A retail
// collect-link payment has a Core-owned business intent and a Finance-owned
// gateway attempt; mixing the two makes retry and reconciliation unsafe.
const RETAIL_PAYMENT_ATTEMPT_STATUS = [
    'CREATED',
    'ORDER_CREATING',
    'CHECKOUT_READY',
    'PAYMENT_PENDING',
    'PAYMENT_SUCCEEDED',
    'PAYMENT_FAILED',
    'PAYMENT_CANCELLED',
    'SETTLEMENT_PENDING',
    'SETTLED',
    'EXPIRED',
];

function isSafePositiveInteger(value) {
    return Number.isSafeInteger(value) && value > 0;
}

const retailPaymentAttemptSchema = new mongoose.Schema(
    {
        // Generated by Finance and used as the durable idempotency boundary for
        // gateway order creation and settlement delivery.
        financeAttemptId: {
            type: String,
            required: true,
            unique: true,
            immutable: true,
            default: () => randomUUID(),
        },

        // `intentId` is the preferred Core v2 name. `collectLinkId` keeps this
        // additive schema compatible with the current Core collect-link model.
        intentId: {
            type: String,
            default: null,
        },
        collectLinkId: {
            type: String,
            default: null,
        },

        provider: {
            type: String,
            required: true,
            uppercase: true,
            trim: true,
        },
        gatewayConfigId: {
            type: String,
            default: null,
            index: true,
        },
        credentialVersion: {
            type: String,
            default: null,
        },

        // All durable retail amounts are paise, never floating-point rupees.
        amountPaise: {
            type: Number,
            required: true,
            min: 1,
            validate: {
                validator: isSafePositiveInteger,
                message: 'amountPaise must be a positive safe integer',
            },
        },
        currency: {
            type: String,
            required: true,
            default: 'INR',
            uppercase: true,
            trim: true,
            maxlength: 3,
        },

        merchantOrderId: {
            type: String,
            default: null,
        },
        gatewayOrderId: {
            type: String,
            default: null,
        },
        gatewayPaymentId: {
            type: String,
            default: null,
        },
        paymentMethod: {
            type: String,
            default: null,
            maxlength: 64,
        },

        status: {
            type: String,
            enum: RETAIL_PAYMENT_ATTEMPT_STATUS,
            default: 'CREATED',
            required: true,
        },
        // Used by a partial unique index to stop two browser tabs from creating
        // separate active orders for the same Core intent.
        isActive: {
            type: Boolean,
            default: true,
        },
        expiresAt: {
            type: Date,
            default: null,
        },
        nextReconcileAt: { type: Date, default: () => new Date(Date.now() + 60000) },
        paidAt: {
            type: Date,
            default: null,
        },

        // This is gateway checkout data only (never a credential). select:false
        // prevents normal list queries from materialising potentially large data.
        checkout: {
            type: mongoose.Schema.Types.Mixed,
            default: null,
            select: false,
        },
        gatewayResponse: {
            type: mongoose.Schema.Types.Mixed,
            default: null,
            select: false,
        },
        failureCode: {
            type: String,
            default: null,
            maxlength: 128,
        },
        failureReason: {
            type: String,
            default: null,
            maxlength: 2000,
        },
        metadata: {
            type: mongoose.Schema.Types.Mixed,
            default: {},
            select: false,
        },
    },
    {
        timestamps: true,
        strict: 'throw',
    }
);

retailPaymentAttemptSchema.pre('validate', function validateCoreIntent(next) {
    if (!this.intentId && !this.collectLinkId) {
        this.invalidate('intentId', 'Either intentId or collectLinkId is required');
    }
    next();
});

// At most one in-flight attempt can own a Core intent. Terminal attempts must
// be marked isActive=false by the checkout/webhook service.
retailPaymentAttemptSchema.index(
    { intentId: 1, isActive: 1 },
    {
        unique: true,
        partialFilterExpression: { intentId: { $type: 'string' }, isActive: true },
        name: 'retail_active_attempt_per_intent',
    }
);
retailPaymentAttemptSchema.index(
    { collectLinkId: 1, isActive: 1 },
    {
        unique: true,
        partialFilterExpression: { collectLinkId: { $type: 'string' }, isActive: true },
        name: 'retail_active_attempt_per_collect_link',
    }
);
retailPaymentAttemptSchema.index(
    { provider: 1, merchantOrderId: 1 },
    {
        unique: true,
        partialFilterExpression: { merchantOrderId: { $type: 'string' } },
        name: 'retail_provider_merchant_order_unique',
    }
);
retailPaymentAttemptSchema.index(
    { provider: 1, gatewayOrderId: 1 },
    {
        unique: true,
        partialFilterExpression: { gatewayOrderId: { $type: 'string' } },
        name: 'retail_provider_gateway_order_unique',
    }
);
retailPaymentAttemptSchema.index(
    { provider: 1, gatewayPaymentId: 1 },
    {
        unique: true,
        partialFilterExpression: { gatewayPaymentId: { $type: 'string' } },
        name: 'retail_provider_gateway_payment_unique',
    }
);
retailPaymentAttemptSchema.index({ status: 1, expiresAt: 1 });
retailPaymentAttemptSchema.index({ status: 1, nextReconcileAt: 1 });

module.exports = retailPaymentAttemptSchema;
module.exports.RETAIL_PAYMENT_ATTEMPT_STATUS = RETAIL_PAYMENT_ATTEMPT_STATUS;
